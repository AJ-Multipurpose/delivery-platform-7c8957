export function recordLabel(value: string, lang: string): string {
  const t = lang === "sw" ? strings.sw : strings.en;
  const labels: Record<string, string> = {
    all: t.allStatuses,
    placed: t.placedStatus,
    accepted: t.acceptedStatus,
    ready: t.readyStatus,
    picked_up: t.pickedUpStatus,
    delivered: t.deliveredStatus,
    cancelled: t.cancelledStatus,
    pending: t.pending,
    approved: t.approvedStatus,
    rejected: t.rejectedStatus,
    paid: t.paidStatus,
    suspended: t.suspendedStatus,
    delivery: t.deliveryEntry,
    sale: t.saleEntry,
    expense: t.expenseEntry,
    withdrawal: t.withdrawalEntry,
  };
  if (value.startsWith("expense: "))
    return t.expenseEntry + ": " + value.slice(9);
  return labels[value] || value;
}

export function locationErrorLabel(code: number, lang: string): string {
  const t = lang === "sw" ? strings.sw : strings.en;
  if (code === 1) return t.locationDenied;
  if (code === 2) return t.locationNotFound;
  if (code === 3) return t.locationTimeout;
  return t.locationUnavailable;
}
